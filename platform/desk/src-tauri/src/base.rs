use engine::error::{Code, Failure, Result};
use engine::process::{Args, Boot};
use engine::thread::Runtime;
use std::io::{Write as _, stdout};
use tauri::webview::PageLoadEvent;
use tauri::{Builder, generate_context, generate_handler};

use crate::arch::{Desk, Faults};
use crate::host;

impl Desk {

    pub(crate) fn run () -> Result<()> {

        let args = Args::current();

        if let Some(line) = args.version("desk", env!("CARGO_PKG_VERSION")) {

            stdout().lock().write_all(line.as_bytes())?;
            return Ok(());

        }

        Failure::ensure(args.is_bare(), Code::Usage, "desk takes no arguments; it is configured by DESK_* variables")?;

        let env  = Runtime::run(Boot::env())?;
        let desk = Self { log: Boot::log(&env, "DESK", "desk")? };

        desk.open()

    }

    #[expect(clippy::disallowed_methods, clippy::disallowed_macros, clippy::large_stack_frames, reason = "the context and the handler are generated by tauri's macros, which unwrap, print and exit on their own")]
    #[cfg_attr(not(test), expect(clippy::wildcard_imports, reason = "the handler glue tauri generates imports its kinds wholesale, outside the test harness"))]
    fn open ( self ) -> Result<()> {

        self.log.info("opening").emit();

        let ready  = self.log.clone();
        let loaded = self.log.clone();

        let outcome = Builder::default()
            .setup(move |_app| { ready.info("ready").emit(); Ok(()) })
            .on_page_load(move |_webview, payload| if payload.event() == PageLoadEvent::Finished { loaded.info("loaded").field("url", payload.url().as_str()).emit(); })
            .invoke_handler(generate_handler![host::host_info])
            .run(generate_context!())
            .map_err(|error| Faults::HOST_FAILED.fail().caused_by(error));

        self.log.info("closed").emit();
        self.log.flush()?;

        outcome

    }

}
